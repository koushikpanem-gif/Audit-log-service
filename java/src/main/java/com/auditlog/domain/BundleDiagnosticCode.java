package com.auditlog.domain;

/**
 * Offline verifier diagnostic codes. The small-bundle verifier emits only the first twenty
 * (the normative small v1 set); the export-set verifier additionally emits the CHUNK_*,
 * TOTAL_COUNT_MISMATCH and CHUNKS_DIGEST_MISMATCH codes.
 */
public enum BundleDiagnosticCode {
    BUNDLE_SCHEMA_INVALID,
    UNSUPPORTED_FORMAT,
    UNSUPPORTED_ALGORITHM,
    RESOURCE_LIMIT_EXCEEDED,
    TRUSTED_KEY_REQUIRED,
    SIGNER_KEY_MISMATCH,
    KEY_ID_MISMATCH,
    BUNDLE_SIGNATURE_INVALID,
    CHECKPOINT_SIGNATURE_INVALID,
    GENESIS_MISMATCH,
    RECORD_COUNT_MISMATCH,
    RECORDS_DIGEST_MISMATCH,
    RECORD_ORDER_INVALID,
    RECORD_OUT_OF_RANGE,
    LEAF_COMMITMENT_MISMATCH,
    CONTENT_HASH_MISMATCH,
    CHAIN_HASH_MISMATCH,
    CHAIN_LINK_BROKEN,
    CHECKPOINT_MISMATCH,
    SELECTION_MISMATCH,
    CHUNK_MISSING,
    CHUNK_DIGEST_MISMATCH,
    CHUNK_ORDER_INVALID,
    CHUNK_COUNT_MISMATCH,
    CHUNK_NAME_UNSAFE,
    CHUNK_UNEXPECTED,
    TOTAL_COUNT_MISMATCH,
    CHUNKS_DIGEST_MISMATCH
}
