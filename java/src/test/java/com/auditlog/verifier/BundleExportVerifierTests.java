    private BundleVerifier.Result pinned(byte[] bundle) {
        return BundleVerifier.verify(bundle, BundleVerifier.Options.pinned(signer.publicKeyBase64()));
    }

    private static Map<String, Object> parse(byte[] bundle) throws Exception {
        return JSON.readValue(bundle, new TypeReference<Map<String, Object>>() { });
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> records(Map<String, Object> bundle) {
        return (List<Map<String, Object>>) bundle.get("records");
    }

    private static byte[] jcs(Object value) throws Exception {
        return CanonicalJson.canonicalize(value, 32, Integer.MAX_VALUE);
    }

    private static byte[] plain(Map<String, Object> bundle) throws Exception {
        return JSON.writeValueAsBytes(bundle);
    }

    /** Signs the body as a malicious or buggy signer would, optionally recomputing count and digest. */
    private static byte[] resign(Map<String, Object> bundle, CheckpointSigner with, boolean recompute)
            throws Exception {
        bundle.remove("signature");
        if (recompute) {
            bundle.put("recordCount", records(bundle).size());
            bundle.put("recordsDigest", HexFormat.of().formatHex(
                    MessageDigest.getInstance("SHA-256").digest(jcs(bundle.get("records")))));
        }
        bundle.put("signature", with.signMessage(bundle, Integer.MAX_VALUE));
        return plain(bundle);
    }

    private static boolean has(BundleVerifier.Result result, BundleDiagnosticCode code) {
        return result.diagnostics().stream().anyMatch(d -> d.code() == code);
    }

    private long eventCount() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:sqlite:" + directory.resolve("audit.db"));
                Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM audit_events")) {
            rows.next();
            return rows.getLong(1);
        }
    }

    private long checkpointCount() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:sqlite:" + directory.resolve("audit.db"));
                Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM checkpoints")) {
            rows.next();
            return rows.getLong(1);
        }
    }

    // ---- builder / verifier round trips (internal consistency only) ----

    @Test
    void roundTripVerifiesWithPinnedKeyAndShapesMatchContract() throws Exception {
        seed();
        byte[] bundle = exportActor("alice");
        BundleVerifier.Result result = pinned(bundle);
        assertEquals(BundleVerifier.Status.VERIFIED, result.status(), result.diagnostics().toString());
        assertTrue(result.originTrusted());
        assertEquals(3, result.recordCount());

        Map<String, Object> parsed = parse(bundle);
        assertArrayEquals(jcs(parsed), bundle, "response bytes are the canonical form");
        @SuppressWarnings("unchecked")
        Map<String, Object> completeness = (Map<String, Object>) parsed.get("completeness");
        assertEquals(5L, ((Number) completeness.get("throughSeq")).longValue());
        assertEquals("NOT_PROVEN", completeness.get("upstreamCoverage"));
        @SuppressWarnings("unchecked")
        Map<String, Object> head = (Map<String, Object>) parsed.get("headCheckpoint");
        assertEquals(6L, ((Number) head.get("seq")).longValue(), "checkpoint is at post-event head");
        assertEquals(parsed.get("exportedAt"), head.get("createdAt"));
        assertEquals(8, ((Map<?, ?>) parsed.get("selection")).size());
    }

    @Test
    void trustModes() throws Exception {
        seed();
        byte[] bundle = exportActor("alice");
        BundleVerifier.Result untrusted = BundleVerifier.verify(bundle, BundleVerifier.Options.selfAsserted());
        assertEquals(BundleVerifier.Status.INTEGRITY_VALID_ORIGIN_UNTRUSTED, untrusted.status());
        assertFalse(untrusted.originTrusted());
        assertFalse(untrusted.notices().isEmpty());

        BundleVerifier.Result missing = BundleVerifier.verify(bundle, BundleVerifier.Options.unconfigured());
        assertEquals(BundleVerifier.Status.INVALID, missing.status());
        assertTrue(has(missing, BundleDiagnosticCode.TRUSTED_KEY_REQUIRED));

        CheckpointSigner other = CheckpointSigner.fromFiles(
                directory.resolve("other/private.pem"), directory.resolve("other/public.b64"), "dev");
        BundleVerifier.Result wrong = BundleVerifier.verify(
                bundle, BundleVerifier.Options.pinned(other.publicKeyBase64()));
        assertEquals(BundleVerifier.Status.INVALID, wrong.status());
        assertTrue(has(wrong, BundleDiagnosticCode.SIGNER_KEY_MISMATCH));
    }

    @Test
    void attackerResignedWithEmbeddedKeyFailsPinnedButPassesSelfAsserted() throws Exception {
        seed();
        Map<String, Object> bundle = parse(exportActor("alice"));
        CheckpointSigner attacker = CheckpointSigner.fromFiles(
                directory.resolve("atk/private.pem"), directory.resolve("atk/public.b64"), "dev");
        bundle.put("signer", Map.of("keyId", attacker.keyId(), "publicKey", attacker.publicKeyBase64()));
        byte[] forged = resign(bundle, attacker, false);
        assertEquals(BundleVerifier.Status.INVALID, pinned(forged).status());
        assertTrue(has(pinned(forged), BundleDiagnosticCode.SIGNER_KEY_MISMATCH));
        BundleVerifier.Result untrusted = BundleVerifier.verify(forged, BundleVerifier.Options.selfAsserted());
        assertFalse(untrusted.originTrusted());
        assertEquals(BundleVerifier.Status.INVALID, untrusted.status(),
                "real-key checkpoint does not match the attacker's embedded key");
        assertTrue(has(untrusted, BundleDiagnosticCode.KEY_ID_MISMATCH)
                || has(untrusted, BundleDiagnosticCode.CHECKPOINT_SIGNATURE_INVALID),
                untrusted.diagnostics().toString());
    }

