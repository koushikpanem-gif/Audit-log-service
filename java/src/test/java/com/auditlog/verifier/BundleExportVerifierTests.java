    private static Path fixtures() {
        Path dir = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        while (dir != null) {
            Path candidate = dir.resolve("python/tests/fixtures/bundle_vectors");
            if (Files.isDirectory(candidate)) {
                return candidate;
            }
            dir = dir.getParent();
        }
        throw new IllegalStateException("fixtures not found");
    }

    private static byte[] fixture(String name) throws Exception {
        return Files.readAllBytes(fixtures().resolve(name));
    }

    private static String goldenKey() throws Exception {
        return Files.readString(fixtures().resolve("test_key_public.b64")).strip();
    }

    @Test
    void goldenFixturesVerifyWithPinnedTestKey() throws Exception {
        BundleVerifier.Options options = BundleVerifier.Options.pinned(goldenKey());
        BundleVerifier.Result gapped = BundleVerifier.verify(fixture("gapped.json"), options);
        assertEquals(BundleVerifier.Status.VERIFIED, gapped.status(), gapped.diagnostics().toString());
        assertEquals(2, gapped.recordCount());
        assertEquals(0, gapped.undisclosedLeafCount());

        BundleVerifier.Result partial = BundleVerifier.verify(fixture("partial.json"), options);
        assertEquals(BundleVerifier.Status.VERIFIED, partial.status(), partial.diagnostics().toString());
        assertEquals(1, partial.undisclosedLeafCount());

        BundleVerifier.Result empty = BundleVerifier.verify(fixture("empty.json"), options);
        assertEquals(BundleVerifier.Status.VERIFIED, empty.status(), empty.diagnostics().toString());
        assertEquals(0, empty.recordCount());
    }

