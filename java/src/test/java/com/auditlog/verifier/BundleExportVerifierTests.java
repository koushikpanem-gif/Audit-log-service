    @Test
    void goldenFixtureTamperingIsDetected() throws Exception {
        BundleVerifier.Options options = BundleVerifier.Options.pinned(goldenKey());
        Map<String, Object> bundle = parse(fixture("gapped.json"));
        records(bundle).get(0).put("eventType", "FORGED");
        assertTrue(has(BundleVerifier.verify(plain(bundle), options), BundleDiagnosticCode.BUNDLE_SIGNATURE_INVALID));

        CheckpointSigner golden = CheckpointSigner.fromPem(fixture("test_key_private.pem"), goldenKey());
        byte[] resigned = resign(bundle, golden, true);
        assertTrue(has(BundleVerifier.verify(resigned, options), BundleDiagnosticCode.CONTENT_HASH_MISMATCH));
    }

    @Test
    void goldenKeyMatchesRfc8032Vector() throws Exception {
        Map<String, Object> vectors = parse(fixture("vectors.json"));
        @SuppressWarnings("unchecked")
        Map<String, Object> rfc = (Map<String, Object>) vectors.get("rfc8032Test1");
        byte[] publicKey = HexFormat.of().parseHex((String) rfc.get("public"));
        byte[] signature = HexFormat.of().parseHex((String) rfc.get("signatureHex"));
        assertTrue(CheckpointSigner.verifyRaw(new byte[0],
                java.util.Base64.getEncoder().encodeToString(signature), publicKey));
        assertEquals(vectors.get("keyId"), CheckpointSigner.keyIdFor(publicKey));
        assertEquals(vectors.get("publicKeyBase64"),
                java.util.Base64.getEncoder().encodeToString(publicKey));
    }

