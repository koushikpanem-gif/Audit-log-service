    @Test
    void resignedInconsistentBodiesYieldPreciseDiagnostics() throws Exception {
        seed();
        byte[] original = exportActor("alice");

        Map<String, Object> altered = parse(original);
        records(altered).get(1).put("eventType", "FORGED");
        BundleVerifier.Result content = pinned(resign(altered, signer, true));
        assertTrue(has(content, BundleDiagnosticCode.CONTENT_HASH_MISMATCH), content.diagnostics().toString());

        Map<String, Object> reordered = parse(original);
        List<Map<String, Object>> recs = records(reordered);
        Map<String, Object> first = recs.get(0);
        recs.set(0, recs.get(1));
        recs.set(1, first);
        assertTrue(has(pinned(resign(reordered, signer, true)), BundleDiagnosticCode.RECORD_ORDER_INVALID));

        Map<String, Object> duplicate = parse(original);
        records(duplicate).add(new java.util.LinkedHashMap<>(records(duplicate).get(2)));
        assertTrue(has(pinned(resign(duplicate, signer, true)), BundleDiagnosticCode.RECORD_ORDER_INVALID));

        Map<String, Object> badDigest = parse(original);
        badDigest.put("recordsDigest", "0".repeat(64));
        assertTrue(has(pinned(resign(badDigest, signer, false)), BundleDiagnosticCode.RECORDS_DIGEST_MISMATCH));

        Map<String, Object> badCount = parse(original);
        badCount.put("recordCount", 99);
        assertTrue(has(pinned(resign(badCount, signer, false)), BundleDiagnosticCode.RECORD_COUNT_MISMATCH));

        Map<String, Object> outOfRange = parse(original);
        @SuppressWarnings("unchecked")
        Map<String, Object> completeness = (Map<String, Object>) outOfRange.get("completeness");
        completeness.put("throughSeq", 2);
        assertTrue(has(pinned(resign(outOfRange, signer, false)), BundleDiagnosticCode.RECORD_OUT_OF_RANGE));

        Map<String, Object> wrongSelection = parse(original);
        records(wrongSelection).get(0).put("actorId", "bob");
        BundleVerifier.Result selection = pinned(resign(wrongSelection, signer, true));
        assertTrue(has(selection, BundleDiagnosticCode.SELECTION_MISMATCH));

        Map<String, Object> badLeaf = parse(original);
        @SuppressWarnings("unchecked")
        Map<String, Map<String, Object>> leaves =
                (Map<String, Map<String, Object>>) records(badLeaf).get(0).get("disclosedLeaves");
        leaves.values().iterator().next().put("value", "tampered");
        assertTrue(has(pinned(resign(badLeaf, signer, true)), BundleDiagnosticCode.LEAF_COMMITMENT_MISMATCH));

        Map<String, Object> unsupported = parse(original);
        unsupported.put("hashVersion", 2);
        assertTrue(has(pinned(resign(unsupported, signer, false)), BundleDiagnosticCode.UNSUPPORTED_ALGORITHM));
    }

    @Test
    void schemaViolationsAreRejected() throws Exception {
        seed();
        byte[] original = exportActor("alice");

        Map<String, Object> extra = parse(original);
        extra.put("surprise", 1);
        assertTrue(has(pinned(resign(extra, signer, false)), BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));

        Map<String, Object> missing = parse(original);
        missing.remove("selection");
        assertTrue(has(pinned(resign(missing, signer, false)), BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));

        Map<String, Object> format = parse(original);
        format.put("format", "audit-export-bundle/v2");
        assertTrue(has(pinned(resign(format, signer, false)), BundleDiagnosticCode.UNSUPPORTED_FORMAT));

        Map<String, Object> timestamp = parse(original);
        timestamp.put("exportedAt", "2026-01-02T03:04:05Z");
        assertTrue(has(pinned(resign(timestamp, signer, false)), BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));

        Map<String, Object> unsafe = parse(original);
        String unsafeText = new String(original, StandardCharsets.UTF_8)
                .replace("\"recordCount\":3", "\"recordCount\":9007199254740992");
        assertTrue(has(pinned(unsafeText.getBytes(StandardCharsets.UTF_8)),
                BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));
        assertFalse(unsafe.isEmpty());

        String duplicateKeys = new String(original, StandardCharsets.UTF_8)
                .replaceFirst("\\{", "{\"format\":\"x\",");
        assertTrue(has(pinned(duplicateKeys.getBytes(StandardCharsets.UTF_8)),
                BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));

        assertTrue(has(pinned("not json".getBytes(StandardCharsets.UTF_8)),
                BundleDiagnosticCode.BUNDLE_SCHEMA_INVALID));
    }

