import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * Cross-language interoperability. Python-signed fixtures (generated by
 * python/tests/fixtures/generate_verifier_vectors.py) are verified here by the Java verifier.
 * Java-signed fixtures are frozen under python/tests/fixtures/java_signed and verified by the
 * Python verifier; they use the public RFC 8032 test key and random salts, so they are
 * regenerated only deliberately with -Daudit.regenerateInteropFixtures=true.
 */
class PythonInteropTests {

    private static final String LEDGER_ID = "java-interop-ledger-\u00e9";
    private static final Instant START = Instant.parse("2030-02-03T04:05:06.123456Z");

    @TempDir
    Path directory;

    private static Path fixtures() {
        Path dir = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        while (dir != null) {
            Path candidate = dir.resolve("python/tests/fixtures");
            if (Files.isDirectory(candidate)) {
                return candidate;
            }
            dir = dir.getParent();
        }
        throw new IllegalStateException("fixtures not found");
    }

    private static String testKey() throws IOException {
        return Files.readString(fixtures().resolve("bundle_vectors/test_key_public.b64")).strip();
    }

    @Test
    void javaVerifiesPythonSignedBundle() throws Exception {
        Path bundle = fixtures().resolve("python_signed/bundle.json");
        Result result = BundleVerifier.verify(Files.readAllBytes(bundle), Options.pinned(testKey()));
        assertEquals(Status.VERIFIED, result.status(), result.diagnostics().toString());
        assertEquals(3, result.recordCount());
        assertEquals(1, result.undisclosedLeafCount());
    }

    @Test
    void javaVerifiesPythonSignedExportSet() throws Exception {
        Path manifest = fixtures().resolve("python_signed/export_set/manifest.json");
        Result result = ExportSetVerifier.verify(manifest, Options.pinned(testKey()));
        assertEquals(Status.VERIFIED, result.status(), result.diagnostics().toString());
        assertEquals(3, result.recordCount());
        assertEquals(1, result.undisclosedLeafCount());
    }

    @Test
    void javaRejectsPythonSignedEvidenceUnderWrongOrMissingKey() throws Exception {
        CheckpointSigner other = CheckpointSigner.fromFiles(
                directory.resolve("other/private.pem"), directory.resolve("other/public.b64"), "dev");
        Path bundle = fixtures().resolve("python_signed/bundle.json");
        byte[] bytes = Files.readAllBytes(bundle);
        assertEquals(Status.INVALID,
                BundleVerifier.verify(bytes, Options.pinned(other.publicKeyBase64())).status());
        assertEquals(Status.INVALID, BundleVerifier.verify(bytes, Options.unconfigured()).status());
        assertEquals(Status.INTEGRITY_VALID_ORIGIN_UNTRUSTED,
                BundleVerifier.verify(bytes, Options.selfAsserted()).status());
    }

    @Test
    void regenerateJavaSignedFixtures() throws Exception {
        assumeTrue(Boolean.getBoolean("audit.regenerateInteropFixtures"),
                "set -Daudit.regenerateInteropFixtures=true to rewrite frozen Java-signed fixtures");
        CheckpointSigner signer = CheckpointSigner.fromPem(
                Files.readAllBytes(fixtures().resolve("bundle_vectors/test_key_private.pem")), testKey());
        Map<String, String> env = new HashMap<>();
        env.put("AUDIT_LEDGER_ID", LEDGER_ID);
        env.put("AUDIT_DB_PATH", directory.resolve("audit.db").toString());
        env.put("AUDIT_EXPORT_DIR", directory.resolve("exports").toString());
        env.put("AUDIT_EXPORT_CHUNK_MAX_RECORDS", "2");
        AuditConfiguration configuration = AuditConfiguration.fromEnvironment(env);
        JdbcAuditRepository repository = new JdbcAuditRepository(directory.resolve("audit.db"), LEDGER_ID);
        AppendEventService append = new AppendEventService(
                repository, configuration, signer, Clock.fixed(START, ZoneOffset.UTC));

        Map<String, Object> rich = new LinkedHashMap<>();
        rich.put("text", "Zo\u00eb \u20ac \uD834\uDD1E \u2028 tab\t");
        rich.put("nothing", null);
        rich.put("double", 0.1);
        rich.put("big", 1e21);
        rich.put("tiny", 1e-7);
        rich.put("safeMax", 9007199254740991L);
        rich.put("emptyObject", Map.of());
        rich.put("emptyArray", List.of());
        rich.put("k/~", Map.of("a", new ArrayList<>(java.util.Arrays.asList(Map.of(), List.of(), null, 1.5, "x"))));
        put(append, "alice", "d1", rich);
        put(append, "bob", "d2", Map.of("n", 1));
        put(append, "alice", "d3", Map.of("k", new ArrayList<>(java.util.Arrays.asList((Object) null))));

        Path out = fixtures().resolve("java_signed");
        Files.createDirectories(out.resolve("export_set"));
        ExportBundleService bundles = new ExportBundleService(repository, configuration, signer, append);
        BundleSelection selection = BundleSelection.forExport("alice", null, null, null, null, null);
        Files.write(out.resolve("bundle.json"), bundles.export(selection, "auditor"));

        ExportSetService sets = new ExportSetService(
                repository, configuration, signer, append, Clock.fixed(START, ZoneOffset.UTC), Runnable::run);
        Map<String, Object> descriptor = sets.create(selection, "auditor");
        Path ready = directory.resolve("exports").resolve("ready").resolve((String) descriptor.get("exportSetId"));
        try (Stream<Path> files = Files.list(ready)) {
            for (Path file : (Iterable<Path>) files::iterator) {
                Files.copy(file, out.resolve("export_set").resolve(file.getFileName().toString()),
                        java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            }
        }
        Result result = ExportSetVerifier.verify(out.resolve("export_set/manifest.json"), Options.pinned(testKey()));
        assertTrue(result.valid(), result.diagnostics().toString());
    }

    private static void put(AppendEventService service, String actor, String resource,
            Map<String, Object> payload) throws Exception {
        service.append(new AppendEventRequest("NOTE", actor, "DOC", resource, payload, null), "writer");
    }
}
